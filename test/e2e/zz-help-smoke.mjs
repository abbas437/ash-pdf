import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
const root = resolve(fileURLToPath(import.meta.url), '..', '..', '..');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.wasm': 'application/wasm', '.png': 'image/png', '.svg': 'image/svg+xml' };
const server = createServer(async (req, res) => { const file = resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://x').pathname)); if (!file.startsWith(root + sep)) { res.writeHead(403).end(); return; } try { res.writeHead(200, { 'content-type': MIME[extname(file)] ?? 'application/octet-stream' }).end(await readFile(file)); } catch { res.writeHead(404).end(); } });
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(`http://127.0.0.1:${server.address().port}/renderer/index.html`);
await page.waitForFunction(() => document.body.dataset.ready === 'true');
await page.keyboard.press('F1');
await page.waitForSelector('.ash-help:not([hidden])');
await page.screenshot({ path: process.argv[2] + '/help-home.png' });
await page.fill('.ah-search', 'text box');
await page.waitForTimeout(200);
console.log('results', await page.$$eval('.ah-result .ah-rt', (x) => x.map((e) => e.textContent).slice(0, 5)));
await page.click('.ah-result');
await page.waitForTimeout(200);
await page.screenshot({ path: process.argv[2] + '/help-topic.png' });
const sm = await page.$('.help-showme'); console.log('showme', !!sm);
if (sm) { await sm.click(); await page.waitForTimeout(400); await page.screenshot({ path: process.argv[2] + '/help-showme.png' }); console.log('spot', await page.$eval('.ah-spot', (e) => e.style.left + ',' + e.style.top).catch(() => 'none'), 'folded', await page.$eval('.ash-help', (e) => e.className)); }
console.log('errors', errs);
await browser.close(); server.close();
